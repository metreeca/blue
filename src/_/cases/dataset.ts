import { boolean, markdown, multiple, optional, reference, required, resource, text } from "../_.js";
import { dct } from "./dct.js";
import { ec2u, Entity, rdfs } from "./ec2u.js";

export function Dataset() {
	return resource(Resource, {

		title: required(text),
		alternative: optional(text),
		description: required(markdown),

		resources: multiple(reference(Resource), {

			foreign: true,

			forward: ec2u.resource,
			reverse: ec2u.dataset

		})

	}, {

		space: dct,
		class: ec2u.Dataset

	});
}

export function Resource() {
	return resource(Entity, {

		generated: optional(boolean, {

			description: { en: "Flags resources wholly or partially generated by AI tools." }

		}),

		dataset: required(reference(Dataset), {

			forward: ec2u,
			reverse: rdfs.member

		})

	}, {

		space: ec2u,
		class: ec2u.Resource

	});
}
